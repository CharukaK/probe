package main

import (
	"encoding/json"
	"flag"
	"fmt"
	"os"
	"sort"
	"strings"
	"text/template"
	"unicode"
)

// NodeType mirrors node-types.json.
type NodeType struct {
	Type     string               `json:"type"`
	Named    bool                 `json:"named"`
	Fields   map[string]FieldSpec `json:"fields,omitempty"`
	Children *ChildSpec           `json:"children,omitempty"`
}

type FieldSpec struct {
	Multiple bool      `json:"multiple"`
	Required bool      `json:"required"`
	Types    []TypeRef `json:"types"`
}

type ChildSpec struct {
	Multiple bool      `json:"multiple"`
	Required bool      `json:"required"`
	Types    []TypeRef `json:"types"`
}

type TypeRef struct {
	Type  string `json:"type"`
	Named bool   `json:"named"`
}

// goType decides the Go type for a field given its spec.
func goType(spec FieldSpec) string {
	if len(spec.Types) == 1 {
		t := pascal(spec.Types[0].Type) + "Node"
		if spec.Multiple {
			return "[]*" + t
		}
		return "*" + t
	}
	// union / multiple possible node kinds
	if spec.Multiple {
		return "[]*ts.Node"
	}
	return "*ts.Node"
}

func pascal(s string) string {
	parts := strings.Split(s, "_")
	for i, p := range parts {
		r := []rune(p)
		if len(r) > 0 {
			r[0] = unicode.ToUpper(r[0])
		}
		parts[i] = string(r)
	}
	return strings.Join(parts, "")
}

var outAstTmpl = template.Must(template.New("ast").Parse(`// Code generated by gen/main.go from node-types.json. DO NOT EDIT.

package {{.Package}}

import ts "github.com/tree-sitter/go-tree-sitter"

type NodeKind string

const (
{{range .Nodes}}
	{{.KindName}} NodeKind = "{{.Type}}"
{{end}}
)

{{range .Nodes}}
// {{.GoName}} represents a {{.Type}} node.
type {{.GoName}} struct {
	TSNode *ts.Node
	{{- range .Fields}}
	{{.GoName}} {{.GoType}} // field: {{.FieldName}}
	{{- end}}
}
{{end}}
`))

type tplData struct {
	Package string
	Nodes   []tplNode
}

type tplNode struct {
	GoName   string
	KindName string
	Type     string
	Fields   []tplField
}

type tplField struct {
	GoName    string
	FieldName string
	GoType    string
}

func main() {
	in := flag.String("in", "", "path to node-types.json")
	out := flag.String("out", "", "output .go file")
	pkg := flag.String("pkg", "ast", "output package name")
	flag.Parse()

	if *in == "" || *out == "" {
		fmt.Fprintln(os.Stderr, "usage: gen -in node-types.json -out ast.go -pkg ast")
		os.Exit(1)
	}

	data, err := os.ReadFile(*in)
	if err != nil {
		fmt.Fprintf(os.Stderr, "error reading file: %v\n", err)
		os.Exit(1)
	}

	var nodes []NodeType
	if err := json.Unmarshal(data, &nodes); err != nil {
		fmt.Fprintf(os.Stderr, "error parsing json: %v\n", err)
		os.Exit(1)
	}

	var named []NodeType
	for _, n := range nodes {
		if n.Named {
			named = append(named, n)
		}
	}

	sort.Slice(named, func(i, j int) bool { return named[i].Type < named[j].Type })

	var views []tplNode
	for _, n := range named {
		v := tplNode{GoName: pascal(n.Type) + "Node", Type: n.Type, KindName: pascal(n.Type) + "Kind"}

		var fieldNames []string
		for fn := range n.Fields {
			fieldNames = append(fieldNames, fn)
		}
		sort.Strings(fieldNames)

		for _, fn := range fieldNames {
			spec := n.Fields[fn]
			v.Fields = append(v.Fields, tplField{
				GoName:    pascal(fn),
				FieldName: fn,
				GoType:    goType(spec),
			})
		}
		views = append(views, v)
	}

	f, err := os.Create(*out)
	if err != nil {
		fmt.Fprintf(os.Stderr, "error creating file: %v\n", err)
		os.Exit(1)
	}
	defer f.Close()

	if err := outAstTmpl.Execute(f, tplData{Package: *pkg, Nodes: views}); err != nil {
		fmt.Fprintf(os.Stderr, "error executing template: %v\n", err)
		os.Exit(1)
	}
}
